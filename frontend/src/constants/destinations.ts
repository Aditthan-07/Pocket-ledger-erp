/**
 * Find destination by district name or id or search string.
 */
export function findDestination(query: string): DestinationConfig {
  const q = (query || '').trim().toLowerCase();
  if (!q) {
    return ALL_DESTINATIONS.find((d) => d.id === 'tn-tiruchirappalli') || ALL_DESTINATIONS[0];
  }

  // Exact ID match
  const byId = ALL_DESTINATIONS.find((d) => d.id.toLowerCase() === q);
  if (byId) return byId;

  // Check if query explicitly indicates an export destination
  const isExplicitExport = q.includes('export') || q.includes('port') || q.includes('lut') || q.includes('seaport');

  // If query does NOT explicitly indicate an export port, prioritize non-export (domestic) destinations first!
  if (!isExplicitExport) {
    // 1. Exact match on name or district or state in non-export destinations
    const nonExportExact = ALL_DESTINATIONS.find(
      (d) =>
        d.type !== 'EXPORT' &&
        (d.name.toLowerCase() === q ||
          (d.district && d.district.toLowerCase() === q) ||
          d.state.toLowerCase() === q)
    );
    if (nonExportExact) return nonExportExact;

    // 2. Partial match in non-export destinations
    const nonExportPartial = ALL_DESTINATIONS.find(
      (d) =>
        d.type !== 'EXPORT' &&
        (d.name.toLowerCase().includes(q) ||
          q.includes(d.name.toLowerCase()) ||
          (d.district && (d.district.toLowerCase().includes(q) || q.includes(d.district.toLowerCase()))))
    );
    if (nonExportPartial) return nonExportPartial;
  } else {
    // If query explicitly indicates an export port, prioritize EXPORT destinations
    const exportMatch = ALL_DESTINATIONS.find(
      (d) =>
        d.type === 'EXPORT' &&
        (d.name.toLowerCase().includes(q) ||
          q.includes(d.name.toLowerCase()) ||
          (d.district && (d.district.toLowerCase().includes(q) || q.includes(d.district.toLowerCase()))))
    );
    if (exportMatch) return exportMatch;
  }

  // Fallback: Exact or partial name match across all destinations
  const byName = ALL_DESTINATIONS.find(
    (d) => d.name.toLowerCase() === q || (d.district && d.district.toLowerCase() === q)
  );
  if (byName) return byName;

  // Fallback: Includes match across all destinations
  const partial = ALL_DESTINATIONS.find(
    (d) => d.name.toLowerCase().includes(q) || (d.district && d.district.toLowerCase().includes(q))
  );
  if (partial) return partial;

  // Dynamic fallback for any party-driven or newly registered destination
  const isTN = q.includes('tamil nadu') || (!q.includes('karnataka') && !q.includes('kerala') && !q.includes('andhra') && !q.includes('telangana'));
  const cityName = query.split(',')[0].trim() || 'Karur';
  return {
    id: `custom-${q.replace(/[^a-z0-9]/g, '-')}`,
    name: query.trim() || 'Karur Factory Hub',
    name_ta: query.trim() || 'கரூர் தொழிற்சாலை மையம்',
    type: isExplicitExport ? 'EXPORT' : isTN ? 'TAMIL_NADU' : 'INTER_STATE',
    state: isExplicitExport ? 'Export' : isTN ? 'Tamil Nadu' : 'Inter-State',
    district: cityName,
    distance_km: isTN ? 135 : 320,
    duration_str: isTN ? '2 hrs 45 min' : '5 hrs 30 min',
    tax_rule: isExplicitExport ? 'Export (0% LUT)' : isTN ? 'CGST+SGST' : 'IGST',
    lat: 10.9601,
    lng: 78.0766,
    highway: 'Direct Transport Corridor',
  };
}
